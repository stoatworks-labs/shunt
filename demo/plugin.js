/**
 * Shunt — browser demo.
 *
 * The four shaders below are copied unedited from `source/Shaders.cpp`,
 * including the `#ifdef SHUNT_EFFECT` branches — the two bundles really are one
 * pair of shaders compiled twice, and the picker in the transport bar compiles
 * them both ways here for the same reason. `withDefines()` inserts the define
 * after the `#version` line exactly as `Shunt.cpp` does, and
 * `demo/tools/check_shaders.py` compares the two copies character for character
 * so they cannot drift.
 *
 * `Queue.cpp` is ported below in full, with `Shapes.cpp`'s extents and bounds
 * and `Controls.cpp`'s 0..1 conversions. That port is the interesting part of
 * this page, because it is the plugin's whole design:
 *
 * **A shape's place is a pure function of (slot, phase).** There is no queue
 * object that shapes are pushed onto and popped off, no "has the one in front
 * left yet?" test, no previous frame. Drag the transport anywhere and the
 * picture is exact, because the frame at phase 91.7 does not need the preceding
 * 91.7 to have been played.
 *
 * What makes that work is the slide speed being derived rather than set:
 * `(1 + 2·margin) / (1 − dwell)` makes every shape's run exactly one cycle long
 * whatever slot it stands at, so `count` shapes released one per `1/count` of a
 * cycle tile the cycle exactly — always that many in play, never a hole and
 * never two shapes wanting one slot.
 */

