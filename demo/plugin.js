/** The padded extent that sizes the quad. Erring high costs overdraw; erring
 *  low silently cuts a corner off a rotated shape. */
function shapeBound(shape) {
  switch (shape) {
    case 0: case 4: case 6: return 1.0;   // Circle, Star, Ring
    case 1: return 1.4143;                // Square: corners at sqrt(2)
    case 2: return 1.0;                   // Triangle
    case 3: return 1.0;                   // Hexagon
    case 5: return 1.05;                  // Cross
    case 7: return 1.05;                  // Bar
    default: return 1.4143;
  }
}

/** The TRUE axis-aligned half extents, unpadded. This is what the Gap control
 *  means by "thickness", so padding here would open a visible space between two
 *  shapes the operator asked to have touching. */
function shapeHalfExtents(shape) {
  switch (shape) {
    case 0: case 6: return [1.0, 1.0];               // Circle, Ring
    case 1: case 5: return [1.0, 1.0];               // Square, Cross
    case 2: return [0.8660254, 0.75];                // Triangle: 1 up, 0.5 down
    case 3: return [1.0, 0.8660254];                 // Hexagon
    case 4: return [0.9510565, 0.9045085];           // Star
    case 7: return [1.0, 0.15];                      // Bar
    default: return [1.0, 1.0];
  }
}

