function withDefines(shader, defines) {
  if (!defines) return shader;
  const afterVersion = shader.indexOf('\n');
  if (afterVersion === -1) return shader;
  return shader.slice(0, afterVersion + 1) + defines + shader.slice(afterVersion + 1);
}

