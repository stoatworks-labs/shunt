const fract = (x) => x - Math.floor(x);
const travelsHorizontally = (side) => side === 0 || side === 1;

/** Short-edge radius to a fraction of each frame axis. Those are the same
 *  number only on a square output, and mixing them up is invisible at 1:1. */
function frameRadius(scale, aspect) {
  return aspect >= 1 ? [scale / aspect, scale] : [scale, scale * aspect];
}

/** The shape's rotation on screen: the direction of travel plus whatever Angle
 *  adds. Measuring Angle from the travel direction is what makes a Bar behave
 *  the same way whichever edge the train comes in from. */
const sideRotation = (side) => [0, Math.PI, Math.PI / 2, -Math.PI / 2][side] ?? 0;

function screenRotation(p) {
  return sideRotation(p.side) + p.angle * Math.PI * 2;
}

/** The rotated box's half extents on the frame's two axes, in frame-span units.
 *  The support function of a rotated box: rotation happens in shape space and
 *  the anisotropic frame scaling comes after it. */
function rotatedHalfExtents(p) {
  const [ex, ey] = shapeHalfExtents(p.shape);
  const hx = ex * Math.max(0, p.stretch);
  const hy = ey;

  const theta = screenRotation(p);
  const c = Math.abs(Math.cos(theta));
  const s = Math.abs(Math.sin(theta));

  const [rx, ry] = frameRadius(p.size, p.aspect);
  return [rx * (hx * c + hy * s), ry * (hx * s + hy * c)];
}

/** Half the shape's extent along the direction of travel. */
function halfThickness(p) {
  const [onX, onY] = rotatedHalfExtents(p);
  return travelsHorizontally(p.side) ? onX : onY;
}

/** Half the shape's extent ACROSS the direction of travel. */
function crossHalfThickness(p) {
  const [onX, onY] = rotatedHalfExtents(p);
  return travelsHorizontally(p.side) ? onY : onX;
}

/** splitmix64's finaliser, in BigInt so it is bit-for-bit the plugin's. A
 *  set's random lane is a pure function of its number. */
const MASK64 = (1n << 64n) - 1n;
function hash01(n) {
  let x = (BigInt.asUintN(64, BigInt(n)) + 0x9E3779B97F4A7C15n) & MASK64;
  x = ((x ^ (x >> 30n)) * 0xBF58476D1CE4E5B9n) & MASK64;
  x = ((x ^ (x >> 27n)) * 0x94D049BB133111EBn) & MASK64;
  x ^= x >> 31n;
  return Number(x >> 11n) / 9007199254740992;
}

/** The set a slot belongs to: every shape released in one cycle shares one. */
function setOf(p, slot) {
  const count = Math.max(1, p.count);
  return Math.floor(p.phase - slot / count);
}

/** Where set `set` runs on the cross axis. Off is Across; Step adds Lane Step
 *  per set; Random moves half the band plus a jitter small enough that two
 *  consecutive sets are never closer than one shape. Both wrap inside the band
 *  where a whole shape stays on the frame. */
function laneAcross(p, set) {
  if (p.lanes === 0) return p.across;

  const e = Math.min(0.45, crossHalfThickness(p));
  const band = 1 - 2 * e;
  const u0 = (p.across - e) / band;

  let u;
  if (p.lanes === 1) {
    u = fract(u0 + (set * p.laneStep) / band);
  } else {
    const sep = Math.min(1, (2 * e) / band);
    const jitter = Math.max(0, 0.5 - sep);
    u = fract(u0 + 0.5 * set + (hash01(set) - 0.5) * jitter);
  }
  return e + u * band;
}

/** Which cell a shape gets, by its release number. Same as PickCell, including
 *  the second hash stream, so a Random pick here is the plugin's pick. */
function pickCell(pick, release, sprite, cellCount) {
  if (cellCount <= 0) return 0;
  let index;
  if (pick === 1) {
    let x = (BigInt.asUintN(64, BigInt(release)) * 0xD1B54A32D192ED03n + 0x632BE59BD9B4E019n) & MASK64;
    x = ((x ^ (x >> 30n)) * 0xBF58476D1CE4E5B9n) & MASK64;
    x = ((x ^ (x >> 27n)) * 0x94D049BB133111EBn) & MASK64;
    x ^= x >> 31n;
    index = Number(x % BigInt(cellCount));
  } else if (pick === 2) {
    index = release + sprite;
  } else {
    index = sprite;
  }
  return ((index % cellCount) + cellCount) % cellCount;
}

/** Centre-to-centre spacing between standing shapes, in frame-span units. At
 *  one thickness they stand edge to edge; below it they overlap. */
function gapSpan(p) {
  if (p.gapUnits === 1) {
    const span = Math.max(1, p.spanPixels);
    return Math.max(0, p.gapValue) / span;
  }
  return Math.max(0, p.gapValue) * 2 * halfThickness(p);
}

const margin = (p) => halfThickness(p) + CLEARANCE;

/** Derived, not a control. This is the whole trick: it makes every shape's run
 *  exactly one cycle long whatever its slot. */
function slideSpeed(p) {
  const idle = Math.max(0.02, 1 - clamp01(p.dwell));
  return (1 + 2 * margin(p)) / idle;
}

/** Clamped so a queue longer than the run backs up off-stage rather than trying
 *  to stand behind its own starting point. */
function slotDepth(p, slot) {
  return Math.max(-margin(p), p.travel - slot * gapSpan(p));
}

/** Slot 0 leads. Slot k was released k/count of a cycle later. */
function slotAge(p, slot) {
  return fract(p.phase - slot / Math.max(1, p.count));
}

function hsvToRgb(h, s, v) {
  h = fract(h) * 6;
  s = clamp01(s);
  v = clamp01(v);

  const sector = Math.floor(h) % 6;
  const f = h - Math.floor(h);
  const p = v * (1 - s);
  const q = v * (1 - s * f);
  const t = v * (1 - s * (1 - f));

  switch (sector) {
    case 0: return [v, t, p];
    case 1: return [q, v, p];
    case 2: return [p, v, t];
    case 3: return [p, q, v];
    case 4: return [t, p, v];
    default: return [v, p, q];
  }
}

function rgbToHsv(r, g, b) {
  const maxC = Math.max(r, g, b);
  const minC = Math.min(r, g, b);
  const d = maxC - minC;

  const v = maxC;
  const s = maxC > 0 ? d / maxC : 0;
  if (d <= 0) return [0, s, v];

  let h;
  if (maxC === r) h = (g - b) / d + (g < b ? 6 : 0);
  else if (maxC === g) h = (b - r) / d + 2;
  else h = (r - g) / d + 4;

  return [h / 6, s, v];
}

/** One shape, by slot. In, stand, out: three straight lines and two thresholds,
 *  which is the whole of the motion. */
function solveSlot(p, slot) {
  const count = Math.max(1, p.count);

  const m = margin(p);
  const v = slideSpeed(p);
  const park = slotDepth(p, slot);
  const dwell = clamp01(p.dwell);
  const age = slotAge(p, slot);

  const set = setOf(p, slot);
  const across = laneAcross(p, set);

  const arrive = (park + m) / v;

  let depth = park;
  let standing = false;

  if (age < arrive) depth = -m + v * age;
  else if (age < arrive + dwell) standing = true;
  else depth = park + v * (age - arrive - dwell);

  // Depth and cross-position to frame space. y runs DOWN, so Top enters at
  // y = 0 and travels towards 1.
  let x;
  let y;
  if (p.side === 0) { x = depth; y = across; }
  else if (p.side === 1) { x = 1 - depth; y = across; }
  else if (p.side === 2) { x = across; y = depth; }
  else { x = across; y = 1 - depth; }

  // Colour is keyed off the SLOT, not the draw order, so a hue spread reads as
  // a stable pattern marching through rather than the whole set flickering
  // every time the queue turns over.
  let r = 1;
  let g = 1;
  let b = 1;

  if (p.colourMode === 1) {
    r = p.r; g = p.g; b = p.b;
  } else if (p.colourMode === 2 || p.colourMode === 3) {
    let [h, s, val] = rgbToHsv(p.r, p.g, p.b);
    // White has no hue and no saturation, so a straight reading of the default
    // swatch would give a train of identical white shapes and look broken.
    if (s < 0.01) {
      s = 1;
      if (val < 0.01) val = 1;
    }
    const along = count > 1 ? slot / count : 0;
    let hue = h + p.hueSpread * along;
    if (p.colourMode === 3) hue += p.phase;
    [r, g, b] = hsvToRgb(hue, s, val);
  }

  return {
    x,
    y,
    scale: Math.max(0, p.size),
    rotation: screenRotation(p),
    r,
    g,
    b,
    a: clamp01(p.opacity),
    slot,
    age,
    depth,
    standing,
    set,
    release: set * count + slot,
  };
}

/** Every shape, in DRAW order: oldest first, newest last.
 *
 *  "The leading edge of #2 slides over the trailing edge of #1" is the whole
 *  reason this sort is here. The order rotates once per release, because which
 *  slot is newest turns over as the phase advances — a fixed order would put
 *  the same shape on top for ever and look wrong for most of every cycle. */
function solve(p) {
  const count = Math.min(MAX_SHAPES, Math.max(1, p.count));
  const out = [];
  for (let slot = 0; slot < count; slot += 1) out.push(solveSlot(p, slot));
  out.sort((a, b) => b.age - a.age);
  return out;
}

